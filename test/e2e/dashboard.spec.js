const { test, expect } = require('@playwright/test');
test('添加、保存、刷新、移除、重置与导入校验', async ({ page }) => {
  await page.goto('/');
  await expect(page.locator('.widget')).toHaveCount(6);
  await expect(page.getByTestId('breakpoint-summary')).toContainText(test.info().project.name === 'mobile' ? 'xxs' : 'lg');
  await page.getByLabel('添加卡片').selectOption('note');
  await page.getByRole('button', { name: '＋ 添加' }).click();
  await expect(page.locator('.widget')).toHaveCount(7);
  await page.getByRole('button', { name: '保存布局', exact: true }).click();
  await expect(page.getByRole('status')).toContainText('已保存');
  await page.reload();
  await expect(page.locator('.widget')).toHaveCount(7);
  await page.getByRole('button', { name: '移除便签', exact: true }).click();
  await expect(page.locator('.widget')).toHaveCount(6);
  await page.getByRole('button', { name: '导入 JSON', exact: true }).click();
  await page.getByLabel('布局 JSON', { exact: true }).fill('{broken');
  await page.getByRole('button', { name: '应用导入' }).click();
  await expect(page.getByRole('status')).toContainText('导入失败');
  await expect(page.locator('.widget')).toHaveCount(6);
  await page.getByRole('button', { name: '取消', exact: true }).click();
  await page.getByRole('button', { name: '锁定布局', exact: true }).click();
  await expect(page.getByRole('button', { name: '＋ 添加' })).toBeDisabled();
  await expect(page.locator('.widget.react-draggable')).toHaveCount(0);
  await page.getByRole('button', { name: '解锁布局', exact: true }).click();
  const download = page.waitForEvent('download');
  await page.getByRole('button', { name: '导出 JSON', exact: true }).click();
  expect((await download).suggestedFilename()).toBe('grid-studio-layout.json');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: `test-results/grid-${test.info().project.name}.png`, fullPage: true });
});
test('真实拖动和缩放会改变布局，保存后保持', async ({ page }, info) => {
  test.skip(info.project.name === 'mobile', '鼠标操作场景；移动端另测响应式与工具栏');
  await page.goto('/');
  const card = page.getByTestId('widget-revenue');
  const before = await card.boundingBox();
  const handle = await card.locator('.widget-handle').boundingBox();
  await page.mouse.move(handle.x + 60, handle.y + 20); await page.mouse.down();
  await page.mouse.move(handle.x + 500, handle.y + 20, { steps: 15 }); await page.mouse.up();
  await expect.poll(async () => (await card.boundingBox()).x).not.toBe(before.x);
  const width = (await card.boundingBox()).width;
  const resize = await card.locator('.react-resizable-handle').boundingBox();
  await page.mouse.move(resize.x + resize.width / 2, resize.y + resize.height / 2); await page.mouse.down();
  await page.mouse.move(resize.x - 110, resize.y + 70, { steps: 15 }); await page.mouse.up();
  await expect.poll(async () => (await card.boundingBox()).width).not.toBe(width);
  await page.getByRole('button', { name: '保存布局', exact: true }).click();
  const stored = await page.evaluate(() => JSON.parse(localStorage.getItem('rgl-studio:v1')).layouts.lg.find(item => item.i === 'revenue'));
  await page.reload();
  await page.getByRole('button', { name: '保存布局', exact: true }).click();
  const restored = await page.evaluate(() => JSON.parse(localStorage.getItem('rgl-studio:v1')).layouts.lg.find(item => item.i === 'revenue'));
  expect(restored).toEqual(stored);
});
